import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {DEFAULT_CONTENT,supabaseEnabled} from '../content-store.js';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=file=>fs.readFileSync(path.join(root,file),'utf8');
const admin=read('admin.html'),site=read('index.html'),adminJS=read('admin.js'),siteJS=read('app.js'),sql=read('docs/supabase.sql');
for(const id of ['adminDrawerScrim','menuToggle','mobileAdminMore','sidebar','saveButton'])assert(admin.includes(`id="${id}"`),`Missing admin ${id}`);
for(const item of ['overview','packages','galleries','enquiries'])assert(admin.includes(`data-mobile-section="${item}"`),`Missing mobile tab ${item}`);
assert(admin.includes('data-section="settings"')&&admin.includes('data-section="enquiries"'));
assert(adminJS.includes('loadEnquiriesPanel')&&adminJS.includes('updateEnquiryStatus'));
for(const key of ['facebook','instagram','youtube','tiktok','tripadvisor','googleReviews'])assert(key in DEFAULT_CONTENT.settings,`Missing settings ${key}`);
assert(site.includes('footerSocialLinks')&&site.includes('name="phone"')&&site.includes('whatsappExplanation'));
assert(siteJS.includes('https://wa.me/')&&siteJS.includes('storeTourEnquiry')&&siteJS.includes('askLiveGuide'));
assert(sql.includes('public.tour_enquiries')&&sql.includes('enable row level security')&&sql.includes('consume_api_quota'));
assert(fs.existsSync(path.join(root,'supabase/functions/travel-ai/index.ts')));
assert(fs.existsSync(path.join(root,'supabase/functions/submit-enquiry/index.ts')));
assert(!supabaseEnabled,'Bundled public config should never contain real credentials');
for(const p of DEFAULT_CONTENT.packages)assert(p.route.every(day=>day.images?.length),'Day photo gallery missing');
console.log('PASS V3: mobile admin, editable socials, WA, leads, Supabase schema/RLS, AI functions, photo days, clean config');
